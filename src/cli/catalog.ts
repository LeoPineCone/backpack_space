/** Writes docs/catalog.md: every hero, item, bag and recipe with the rules text generated from the data. `npm run catalog` */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { describeHero, describeItem, type ItemDef } from "@backpack-space/core";
import { ROOT, loadGameData, loadItemArt } from "@backpack-space/core/node";

const d = loadGameData();
const out: string[] = ["# Catalog", "", "Generated by `npm run catalog` from `data/`. Do not edit by hand.", ""];
const name = (id: string) => d.items.get(id)!.name;
const recipeOf = (it: ItemDef) => d.recipes.find((r) => r.out === it.id);
const row = (it: ItemDef) => {
  const made = recipeOf(it);
  const uses = (d.recipesWith.get(it.id) ?? []).map((r) => name(r.out));
  return `| ${it.name} | ${it.crafted ? `crafted (step ${it.depth})` : it.rarity} | ${it.cost} | \`${it.shape.join("/")}\` | ${it.tags.filter((t) => t !== "crafted" && t !== "bag").join(", ")} | ${describeItem(it, d).join(" ")} | ${made ? `= ${made.in.map(name).join(" + ")}` : ""}${uses.length ? `${made ? "; " : ""}→ ${uses.join(", ")}` : ""} |`;
};
const tableOf = (title: string, items: ItemDef[]) => {
  if (!items.length) return;
  out.push(`### ${title} (${items.length})`, "", "| Item | Rarity | Gold | Shape | Tags | Rules | Recipes |", "|---|---|---|---|---|---|---|", ...items.map(row), "");
};
const order = ["common", "rare", "epic", "legendary", "artifact"];
const sorted = (items: ItemDef[]) => [...items].sort((a, b) => a.depth - b.depth || order.indexOf(a.rarity) - order.indexOf(b.rarity) || a.cost - b.cost);
const all = d.itemList.filter((i) => !i.isBag);
out.push(`${d.heroList.length} heroes, ${all.length} items (${all.filter((i) => i.inShop).length} in the shop, ${all.filter((i) => i.crafted).length} crafted, ${all.filter((i) => i.rarity === "artifact").length} artifacts), ${d.itemList.length - all.length} bags, ${d.recipes.length} recipes.`, "");
out.push("Shape: `#` cell, `*` star, `.` empty; rows separated by `/`. Recipes: `=` what it is made of, `→` what it becomes part of.", "");
out.push("## Heroes", "");
for (const h of d.heroList) {
  out.push(`### ${h.name} – ${h.title}`, "", h.focus, "", ...describeHero(h, d).map((l) => `- ${l}`), `- Starts with: ${[...h.bags, ...h.start].map((p) => name(p.item)).join(", ")}.`, `- Signature artifacts (after round ${d.rules.specials.find((s) => s.pool === "hero")?.afterRound}): ${h.artifacts.map(name).join(", ")}.`, "");
}
out.push("## Bags", "");
tableOf("Bags", d.itemList.filter((i) => i.isBag));
out.push("## General items", "");
for (const tag of ["weapon", "armor", "accessory", "pet", "food"] as const) {
  const main = (i: ItemDef) => (i.tags.includes("pet") ? "pet" : i.tags.includes("food") ? "food" : i.tags.includes("weapon") ? "weapon" : i.tags.includes("armor") ? "armor" : "accessory");
  tableOf(`${tag[0]!.toUpperCase()}${tag.slice(1)}: shop`, sorted(all.filter((i) => !i.hero && i.inShop && main(i) === tag)));
  tableOf(`${tag[0]!.toUpperCase()}${tag.slice(1)}: crafted`, sorted(all.filter((i) => !i.hero && i.crafted && main(i) === tag)));
}
tableOf("General artifacts", all.filter((i) => !i.hero && i.rarity === "artifact"));
out.push("## Hero items", "");
out.push("Provisional: the heroes are being redesigned, so their items, names and pictures may still change.", "");
for (const h of d.heroList) tableOf(h.name, sorted(all.filter((i) => i.hero === h.id)));
writeFileSync(join(ROOT, "docs", "catalog.md"), out.join("\n"));
console.log(`docs/catalog.md written (${all.length} items).`);

// docs/item-art.md: the asset list for item pictures
const art = loadItemArt();
const box = (it: ItemDef) => {
  const cells = it.shape.flatMap((row, y) => [...row].map((c, x) => (c === "#" ? [x, y] : null)).filter((p): p is number[] => p !== null));
  const xs = cells.map((c) => c[0]!), ys = cells.map((c) => c[1]!);
  return `${Math.max(...xs) - Math.min(...xs) + 1}×${Math.max(...ys) - Math.min(...ys) + 1}`;
};
const cellsOf = (it: ItemDef) => it.shape.map((r) => r.replace(/\*/g, ".")).filter((r) => r.includes("#")).join("/");
const artOut: string[] = ["# Item pictures (asset list)", "", "Generated by `npm run catalog` from `data/item-art.json` and `data/items/`. Do not edit by hand: change the brief in `data/item-art.json`.", ""];
artOut.push(
  `${d.itemList.length} pictures: ${all.length} items and ${d.itemList.length - all.length} bags. Hero items are **provisional** (marked ⚠): the heroes are being redesigned, so these items, their names and their look may still change.`, "",
  "## How to draw them", "",
  "- Style: [docs/style.md](style.md) (dark ink comic, flat matte colours, no glow). Start every prompt with its prompt base, then add the brief.",
  "- One item per picture, seen from the front or slightly from above, on a plain background that can be cut out. No text, no frame, no stars.",
  "- The picture fills the item's box: **Box** is width × height in backpack cells. One cell is about 44 px on a phone, so draw at 176 px per cell and keep the silhouette readable at 44 px. Odd shapes (L, T) use the same box; the picture may leave the empty corner free.",
  "- The game turns pictures with the item, so nothing in them has to stay upright (no text, no horizon).",
  "- Each brief ends with one accent colour from the palette; everything else stays in ink, night, bone and muted copper.",
  "- Rarity is shown by the client (frame or background), not in the picture.",
  "- File name: `items/<id>.png`.", "");
const artRow = (it: ItemDef) => `| ${it.hero ? "⚠ " : ""}${it.name} | \`items/${it.id}.png\` | ${it.crafted ? `crafted ${it.depth}` : it.rarity} | ${box(it)} \`${cellsOf(it)}\` | ${art[it.id] ?? "**missing**"} |`;
const artTable = (title: string, items: ItemDef[]) => {
  if (!items.length) return;
  artOut.push(`### ${title} (${items.length})`, "", "| Item | File | Rarity | Box | Picture |", "|---|---|---|---|---|", ...items.map(artRow), "");
};
artOut.push("## Bags", "");
artTable("Bags", d.itemList.filter((i) => i.isBag));
artOut.push("## General items", "");
for (const tag of ["weapon", "armor", "accessory", "pet", "food"] as const) {
  const main = (i: ItemDef) => (i.tags.includes("pet") ? "pet" : i.tags.includes("food") ? "food" : i.tags.includes("weapon") ? "weapon" : i.tags.includes("armor") ? "armor" : "accessory");
  artTable(`${tag[0]!.toUpperCase()}${tag.slice(1)}`, sorted(all.filter((i) => !i.hero && main(i) === tag && i.rarity !== "artifact")));
}
artTable("General artifacts", all.filter((i) => !i.hero && i.rarity === "artifact"));
artOut.push("## Hero items (provisional)", "", "The heroes are being redesigned. Draw these last, after the hero designs are fixed; the briefs may change with them.", "");
for (const h of d.heroList) artTable(h.name, sorted(all.filter((i) => i.hero === h.id)));
writeFileSync(join(ROOT, "docs", "item-art.md"), artOut.join("\n"));
console.log(`docs/item-art.md written (${d.itemList.length} pictures).`);

// docs/glossary.md: every game term in English and German
const g: string[] = ["# Glossary", "", "Generated by `npm run catalog` from `data/glossary.json`. Do not edit by hand.", "",
  "Every game term with the English word used in the game, the docs and the code, the German word for talking about the design, and a short meaning. The client's keyword legend and glossary and the generated rules text take their words from the same file. Numbers come from `data/rules.json`.", "",
  "**In code** names the identifiers in code and data (for example the backpack is `ship` in the effect language). The term id in `data/glossary.json` is also the symbol name in the client.", ""];
for (const grp of d.glossary.groups) {
  const terms = d.glossary.terms.filter((t) => t.group === grp.id);
  if (!terms.length) continue;
  g.push(`## ${grp.title}`, "", "| English | German | Meaning | In code |", "|---|---|---|---|",
    ...terms.map((t) => `| **${t.en}** | ${t.de} | ${t.text.replace(/\|/g, "\\|")} | ${(t.code.length ? t.code : [t.id]).map((c) => `\`${c}\``).join(", ")} |`), "");
}
writeFileSync(join(ROOT, "docs", "glossary.md"), g.join("\n"));
console.log(`docs/glossary.md written (${d.glossary.terms.length} terms).`);
